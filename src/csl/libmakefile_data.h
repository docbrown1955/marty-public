#pragma once

#include <iostream>

void print_libmakefile_data(std::ostream      &out,
                            std::string const &cppCompiler,
                            std::string const &cCompiler,
                            bool               optimize,
                            bool               cppLibrary,
                            bool               quadruple)

{
    out << "# Part common to all libraries generated by CSL\n";
    out << "# Out-of-source build: objects, libraries and executables go to $(BUILDDIR)\n";
    out << "\n";
    out << "CXX     = " << cppCompiler << "\n";
    out << "CC      = " << cCompiler << "\n";
    out << "CXXSTD  = -std=c++17\n";
    out << "CSTD    = -std=c11\n";
    out << "DEFAULTFLAGS = -Wall -Wextra -Wpedantic "
           "-Wno-deprecated-declarations -fPIC\n";

    if (optimize) {
        out << "MATH_OPTI = -Ofast\n\n";
        out << "OPTIFLAGS = -O2 $(MATH_OPTI)\n";
    }
    else {
        out << "OPTIFLAGS = \n";
    }
    out << "CXXFLAGS  = $(CXXSTD) $(DEFAULTFLAGS) -O2\n";
    out << "CFLAGS    = $(CSTD) $(DEFAULTFLAGS) $(OPTIFLAGS)\n";
    out << "LINKFLAGS = $(DEFAULTFLAGS)\n";
    out << "\n";
    out << "# QUAD=1 builds the C calculations in quadruple precision (default: "
        << (quadruple ? 1 : 0) << ")\n";
    out << "QUAD ?= " << (quadruple ? 1 : 0) << "\n";
    out << "ifeq ($(QUAD),1)\n";
    out << "CFLAGS += -DMTY_QUADRUPLE -DQUAD=1 -DQUADSIZE=16 -DCQUADSIZE=16\n";
    out << "LIBS   += -lquadmath\n";
    out << "endif\n";
    out << "\n";
    out << "BUILDDIR = build\n";
    out << "OBJDIR   = $(BUILDDIR)/obj\n";
    out << "SOBJDIR  = $(OBJDIR)/script\n";
    out << "LIBDIR   = $(BUILDDIR)/lib\n";
    out << "BINDIR   = $(BUILDDIR)/bin\n";
    out << "\n";
    out << "SRC      = $(wildcard src/cpp/*.cpp)\n";
    out << "CSRC     = $(wildcard src/c/*.c)\n";
    out << "OBJ      = $(SRC:src/cpp/%.cpp=$(OBJDIR)/%.o)\n";
    out << "COBJ     = $(CSRC:src/c/%.c=$(OBJDIR)/c/%.o)\n";
    out << "SCRIPTS  = $(wildcard script/*.cpp)\n";
    out << "BINARIES = $(SCRIPTS:script/%.cpp=$(BINDIR)/%.x)\n";
    out << "SOBJ     = $(SCRIPTS:script/%.cpp=$(SOBJDIR)/%.o)\n";
    out << "\n";
    out << ".PHONY: all scripts lib install clean\n\n";
    out << "all: scripts lib\n";
    out << "\n";
    out << "scripts: $(BINARIES)\n";
    out << "lib: $(LIBDIR)/$(NAMELIB).so $(LIBDIR)/$(NAMELIB).a\n";
    out << "\n";
    out << "$(OBJDIR)/c/%.o: src/c/%.c\n";
    out << "\t@mkdir -p $(@D)\n";
    out << "\t$(CC) $(CFLAGS) -c $< -o $@ $(INCPATH)\n";
    out << "\n";
    out << "$(OBJDIR)/%.o: src/cpp/%.cpp\n";
    out << "\t@mkdir -p $(@D)\n";
    out << "\t$(CXX) $(CXXFLAGS) -c $< -o $@ $(INCPATH)\n";
    out << "\n";
    out << "$(SOBJDIR)/%.o: script/%.cpp\n";
    out << "\t@mkdir -p $(@D)\n";
    out << "\t$(CXX) $(CXXFLAGS) -c $< -o $@ $(INCPATH)\n";
    out << "\n";
    out << "$(BINDIR)/%.x: $(SOBJDIR)/%.o $(OBJ) $(COBJ)\n";
    out << "\t@mkdir -p $(@D)\n";
    out << "\t$(CXX) $(CXXSTD) $(LINKFLAGS) -o $@ $^ $(INCPATH) "
           "$(LIBPATH) $(LIBS)\n";
    out << "\n";
    // C-only libraries have no C++ objects, so they are linked with the C compiler.
    out << "$(LIBDIR)/$(NAMELIB).so: $(OBJ) $(COBJ)\n";
    out << "\t@mkdir -p $(@D)\n";
    if (cppLibrary)
        out << "\t$(CXX) $(CXXFLAGS) -shared -o $@ $^ $(LIBPATH) "
               "$(LIBS)\n";
    else
        out << "\t$(CC) $(CFLAGS) -shared -o $@ $^ $(LIBPATH) "
               "$(LIBS)\n";
    out << "\n";
    out << "$(LIBDIR)/$(NAMELIB).a: $(OBJ) $(COBJ)\n";
    out << "\t@mkdir -p $(@D)\n";
    out << "\tar rcs $@ $^\n";
    out << "\n";
    out << "install: all\n";
    out << "\t@test -n \"$(INSTALL_DIR)\" || { echo 'Usage: make install INSTALL_DIR=<folder>'; exit 1; }\n";
    out << "\tmkdir -p $(INSTALL_DIR)\n";
    out << "\tcp $(LIBDIR)/$(NAMELIB).so $(BINARIES) $(INSTALL_DIR)/\n";
    out << "\t@echo \"Successful install in $(INSTALL_DIR)\"\n";
    out << "\n";
    out << "clean:\n";
    out << "\trm -rf $(BUILDDIR)\n";
}

