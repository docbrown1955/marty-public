/**
 * @file librarygenerator_python.cpp
 * @brief Python binding writer of the library generator.
 *
 * The binding is a ctypes module that calls the explicit C functions of the
 * C core (c_<name>_explicit). It only converts Python values and checks that
 * the parameters used by a function are set. It holds no numerical logic.
 */

#include "librarygenerator.h"
#include "librarygroup.h"
#include "libraryfunction.h"
#include <algorithm>

namespace csl {

namespace {

struct PythonBinding {
    LibFunction const *function;
    bool               complexReturn;
};

bool hasOnlyRealParameters(LibFunction const &f)
{
    return std::all_of(f.getParameters().begin(),
                       f.getParameters().end(),
                       [](LibParameter const &p) {
                           return p.ctype == LibraryGenerator::crealUsing;
                       });
}

} // namespace

void LibraryGenerator::printPython() const
{
    std::vector<PythonBinding>      bindings;
    std::vector<std::string>        paramNames;
    for (const auto &g : groups) {
        if (g->empty())
            continue;
        for (const auto &f : g->getFunctions()) {
            if (f.isTrivial() || f.isCppFunc() || !hasOnlyRealParameters(f))
                continue;
            bindings.push_back({&f, g->hasComplexReturn()});
            for (const auto &p : f.getParameters())
                if (std::find(paramNames.begin(), paramNames.end(), p.name)
                    == paramNames.end())
                    paramNames.push_back(p.name);
        }
    }

    file py(path + "/" + pyDir + "/" + regLibName() + ".py");
    py << R"PY("""Python binding of the MARTY library )PY" << name
       << R"PY(. Generated by MARTY, do not edit."""

import ctypes
import os
from dataclasses import dataclass
from typing import Optional

_LIBRARY = ctypes.CDLL(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                    os.pardir, "lib", "lib)PY"
       << regLibName() << R"PY(.so"))


class _Complex(ctypes.Structure):
    _fields_ = [("real", ctypes.c_double), ("imag", ctypes.c_double)]


@dataclass
class Params:
    """Library parameters. Unset fields are None; a function checks only the fields it uses."""
)PY";
    for (const auto &p : paramNames)
        py << "    " << p << ": Optional[float] = None\n";
    py << R"PY(

def _collect(function, names, params, keywords):
    values = []
    for name in names:
        value = keywords[name]
        if value is None and params is not None:
            value = getattr(params, name)
        if value is None:
            raise ValueError(f"{function}: parameter '{name}' is not set")
        values.append(float(value))
    return values
)PY";

    for (const auto &b : bindings) {
        LibFunction const &f    = *b.function;
        std::string const  pyName = f.getName();
        std::string const  cName  = "_" + pyName;
        std::vector<LibParameter> const &params = f.getParameters();

        py << "\n\n" << cName << " = _LIBRARY.c_" << pyName << "_explicit\n";
        py << cName << ".argtypes = [";
        for (size_t i = 0; i != params.size(); ++i)
            py << (i ? ", " : "") << "ctypes.c_double";
        py << "]\n";
        py << cName << ".restype = "
           << (b.complexReturn ? "_Complex" : "ctypes.c_double") << "\n\n\n";

        py << "def " << pyName << "(params: Optional[Params] = None";
        for (size_t i = 0; i != params.size(); ++i)
            py << (i ? ", " : ", *, ") << params[i].name
               << ": Optional[float] = None";
        py << ") -> " << (b.complexReturn ? "complex" : "float") << ":\n";
        py << "    values = _collect(\"" << pyName << "\", [";
        for (size_t i = 0; i != params.size(); ++i)
            py << (i ? ", " : "") << '"' << params[i].name << '"';
        py << "], params, {";
        for (size_t i = 0; i != params.size(); ++i)
            py << (i ? ", " : "") << '"' << params[i].name << "\": "
               << params[i].name;
        py << "})\n";
        if (b.complexReturn) {
            py << "    result = " << cName << "(*values)\n";
            py << "    return complex(result.real, result.imag)\n";
        }
        else {
            py << "    return float(" << cName << "(*values))\n";
        }
    }
}

} // namespace csl
